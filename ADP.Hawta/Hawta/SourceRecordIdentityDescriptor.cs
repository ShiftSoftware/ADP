using System.Text.Json.Serialization;

namespace ShiftSoftware.ADP.Hawta;

/// <summary>How Hawta derives the canonical <c>_PrimaryKey</c> from source fields.</summary>
public enum SourcePrimaryKeySemantics
{
    /// <summary>A single projected source column is trimmed and stored as text.</summary>
    SourceColumn,

    /// <summary>One or more normalized logical-key parts form the canonical key.</summary>
    LogicalKey,

    /// <summary>Normalized group parts plus a one-based encounter ordinal identify each occurrence.</summary>
    OccurrenceOrdinal,
}

/// <summary>One source field participating in canonical record identity.</summary>
public sealed record SourceRecordKeyPart(
    [property: JsonPropertyName("column")] string Column,
    [property: JsonPropertyName("normalization")] FileKeyNormalization Normalization);

/// <summary>
/// Structured, publishable explanation of one source's record identity. Public rows carry the
/// resulting canonical key only in <c>_PrimaryKey</c>; this descriptor explains how it was made.
/// </summary>
public sealed record SourceRecordIdentityDescriptor(
    [property: JsonPropertyName("identityKind")] SourceRecordIdentityKind IdentityKind,
    [property: JsonPropertyName("canonicalColumn")] string CanonicalColumn,
    [property: JsonPropertyName("primaryKeyColumn")] string? PrimaryKeyColumn,
    [property: JsonPropertyName("semantics")] SourcePrimaryKeySemantics Semantics,
    [property: JsonPropertyName("keyParts")] IReadOnlyList<SourceRecordKeyPart> KeyParts,
    [property: JsonPropertyName("separator")] string? Separator = null,
    [property: JsonPropertyName("occurrenceOrdinalColumn")] string? OccurrenceOrdinalColumn = null)
{
    /// <summary>A database-owned key projected by <paramref name="primaryKeyColumn"/>.</summary>
    public static SourceRecordIdentityDescriptor DatabaseKey(string primaryKeyColumn) =>
        FromSourceColumn(SourceRecordIdentityKind.DatabaseKey, primaryKeyColumn);

    /// <summary>A source-projected logical key, such as a SQL view's computed LINEKEY.</summary>
    public static SourceRecordIdentityDescriptor LogicalKey(string primaryKeyColumn) =>
        FromSourceColumn(SourceRecordIdentityKind.LogicalKey, primaryKeyColumn);

    /// <summary>A logical key generated by the common file ingestor.</summary>
    public static SourceRecordIdentityDescriptor LogicalKey(FileLogicalKey logicalKey)
    {
        ArgumentNullException.ThrowIfNull(logicalKey);
        return new(
            SourceRecordIdentityKind.LogicalKey,
            BookkeepingColumns.PrimaryKey,
            logicalKey.Parts.Count == 1 ? logicalKey.Parts[0].Column : null,
            SourcePrimaryKeySemantics.LogicalKey,
            [.. logicalKey.Parts.Select(ToPublishedPart)],
            logicalKey.Separator);
    }

    /// <summary>An explicit no-stable-lineage occurrence identity generated by the file ingestor.</summary>
    public static SourceRecordIdentityDescriptor OccurrenceOrdinal(FileOccurrenceRowIdentity identity)
    {
        ArgumentNullException.ThrowIfNull(identity);
        return new(
            SourceRecordIdentityKind.OccurrenceOrdinal,
            BookkeepingColumns.PrimaryKey,
            null,
            SourcePrimaryKeySemantics.OccurrenceOrdinal,
            [.. identity.GroupParts.Select(ToPublishedPart)],
            OccurrenceOrdinalColumn: identity.OrdinalColumn);
    }

    private static SourceRecordIdentityDescriptor FromSourceColumn(
        SourceRecordIdentityKind kind,
        string primaryKeyColumn)
    {
        if (!SnapshotTableDefinition.IsValidIdentifier(primaryKeyColumn))
            throw new ArgumentException("The source primary-key column must be a plain snapshot identifier.", nameof(primaryKeyColumn));

        return new(
            kind,
            BookkeepingColumns.PrimaryKey,
            primaryKeyColumn,
            SourcePrimaryKeySemantics.SourceColumn,
            [new SourceRecordKeyPart(primaryKeyColumn, FileKeyNormalization.Trim)]);
    }

    private static SourceRecordKeyPart ToPublishedPart(FileLogicalKeyPart part) =>
        new(part.Column, part.Normalization);

    internal void Validate(string manifestPath, string table, string sourceKey)
    {
        string Error(string detail) =>
            $"'{manifestPath}' source '{sourceKey}' for table '{table}' has an invalid record-identity contract: {detail}";

        if (!Enum.IsDefined(IdentityKind))
            throw new InvalidDataException(Error($"unknown identity kind '{IdentityKind}'."));
        if (!Enum.IsDefined(Semantics))
            throw new InvalidDataException(Error($"unknown primary-key semantics '{Semantics}'."));
        if (!string.Equals(CanonicalColumn, BookkeepingColumns.PrimaryKey, StringComparison.Ordinal))
            throw new InvalidDataException(Error(
                $"canonicalColumn must be '{BookkeepingColumns.PrimaryKey}', not '{CanonicalColumn}'."));
        if (KeyParts is null || KeyParts.Count == 0)
            throw new InvalidDataException(Error("at least one key part is required."));
        if (KeyParts.Any(part => part is null
                                 || !SnapshotTableDefinition.IsValidIdentifier(part.Column)
                                 || !Enum.IsDefined(part.Normalization)))
            throw new InvalidDataException(Error("key parts must name valid columns and known normalizations."));
        if (KeyParts.Select(part => part.Column).Distinct(StringComparer.OrdinalIgnoreCase).Count() != KeyParts.Count)
            throw new InvalidDataException(Error("key-part columns must be unique."));

        switch (IdentityKind, Semantics)
        {
            case (SourceRecordIdentityKind.DatabaseKey, SourcePrimaryKeySemantics.SourceColumn):
            case (SourceRecordIdentityKind.LogicalKey, SourcePrimaryKeySemantics.SourceColumn):
                if (KeyParts.Count != 1
                    || string.IsNullOrWhiteSpace(PrimaryKeyColumn)
                    || !PrimaryKeyColumn.Equals(KeyParts[0].Column, StringComparison.OrdinalIgnoreCase)
                    || Separator is not null
                    || OccurrenceOrdinalColumn is not null)
                {
                    throw new InvalidDataException(Error(
                        "source-column identity requires one matching primaryKeyColumn and no separator/ordinal."));
                }
                break;

            case (SourceRecordIdentityKind.LogicalKey, SourcePrimaryKeySemantics.LogicalKey):
                var expectedSingleColumn = KeyParts.Count == 1 ? KeyParts[0].Column : null;
                if (!string.Equals(PrimaryKeyColumn, expectedSingleColumn, StringComparison.OrdinalIgnoreCase)
                    || string.IsNullOrEmpty(Separator)
                    || OccurrenceOrdinalColumn is not null)
                {
                    throw new InvalidDataException(Error(
                        "logical-key identity requires its configured separator, no ordinal, and a singular " +
                        "primaryKeyColumn only when it has one part."));
                }
                break;

            case (SourceRecordIdentityKind.OccurrenceOrdinal, SourcePrimaryKeySemantics.OccurrenceOrdinal):
                if (PrimaryKeyColumn is not null
                    || Separator is not null
                    || string.IsNullOrWhiteSpace(OccurrenceOrdinalColumn)
                    || !SnapshotTableDefinition.IsValidIdentifier(OccurrenceOrdinalColumn))
                {
                    throw new InvalidDataException(Error(
                        "occurrence identity requires an ordinal column and no singular primaryKeyColumn/separator."));
                }
                break;

            default:
                throw new InvalidDataException(Error(
                    $"identity kind '{IdentityKind}' is incompatible with semantics '{Semantics}'."));
        }
    }
}
